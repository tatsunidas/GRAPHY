	/**
	 * VolumeData (マスク) から MeshData を生成します。
	 * 
	 * @param volume   マスクデータ (0 or 255)
	 * @param isoLevel 閾値 (通常は127.5)
	 */
	public static MeshData generateMesh(VolumeData volume, float isoLevel) {
		if (volume.dataType != VolumeData.DataType.BYTE) {
			Log.logger.severe("MarchingCubes only supports BYTE masking right now.");
			return null;
		}

		byte[] data = (byte[]) volume.data;
		int w = volume.width;
		int h = volume.height;
		int d = volume.depth;

		// 生成された頂点とインデックスを保持するリスト
		List<Float> vertices = new ArrayList<>();
		List<Integer> indices = new ArrayList<>();

		// 【重要】共有頂点をキャッシュしてインデックス化し、メモリを劇的に節約する
		Map<String, Integer> vertexCache = new HashMap<>();

		// ----------------------------------------------------
		// メインループ：3D空間を1ボクセルずつ「行進」する
		// (端の1ピクセルはキューブが作れないので -1 まで)
		// ----------------------------------------------------
		Vector3f[] cubePositions = new Vector3f[8];
		float[] cubeValues = new float[8];
		Vector3f[] edgeVertices = new Vector3f[12]; // 12本の辺それぞれの交点

		for (int z = 0; z < d - 1; z++) {
			for (int y = 0; y < h - 1; y++) {
				for (int x = 0; x < w - 1; x++) {

					int cubeIndex = 0;

					// 1. 8つの頂点の座標と値を取得し、状態番号(cubeIndex)を計算
					for (int i = 0; i < 8; i++) {
						int vx = x + VERTEX_OFFSETS[i][0];
						int vy = y + VERTEX_OFFSETS[i][1];
						int vz = z + VERTEX_OFFSETS[i][2];

						// 座標は実寸（ピクセル間隔）を掛けて配置
						cubePositions[i] = new Vector3f((float) (vx * volume.pixelSpacingX),
								(float) (vy * volume.pixelSpacingY), (float) (vz * volume.sliceThickness));
						cubeValues[i] = getVoxelValue(data, vx, vy, vz, w, h);

						// 値が閾値以下ならビットを立てる (0〜255のインデックスが完成)
						if (cubeValues[i] < isoLevel) {
							cubeIndex |= (1 << i);
						}
					}

					// 2. 完全に内側、または完全に外側の場合はポリゴンが発生しないのでスキップ
					if (edgeTable[cubeIndex] == 0)
						continue;

					// 3. 交差する辺(エッジ)の正確な交点を計算する
					for (int i = 0; i < 12; i++) {
						// edgeTableで「この辺に交点があるか(ビットが立っているか)」を判定
						if ((edgeTable[cubeIndex] & (1 << i)) != 0) {
							int v1 = EDGE_CONNECTION[i][0];
							int v2 = EDGE_CONNECTION[i][1];

							edgeVertices[i] = vertexInterp(isoLevel, cubePositions[v1], cubePositions[v2],
									cubeValues[v1], cubeValues[v2]);
						}
					}

					// 4. triTableを参照して、交点同士を結び三角形を作る
					for (int i = 0; triTable[cubeIndex][i] != -1; i += 3) {
						for (int j = 0; j < 3; j++) {
							int edgeIdx = triTable[cubeIndex][i + j];
							Vector3f point = edgeVertices[edgeIdx];

							// キャッシュキーとして文字列化 (共有頂点を使い回すため)
							String key = point.x + "," + point.y + "," + point.z;

							if (!vertexCache.containsKey(key)) {
								vertexCache.put(key, vertices.size() / 3);
								vertices.add(point.x);
								vertices.add(point.y);
								vertices.add(point.z);
							}
							indices.add(vertexCache.get(key));
						}
					}
				}
			}
		}

		// 5. データ構築
        Log.logger.info("Marching Cubes Generated " + (indices.size() / 3) + " triangles.");

        float[] vArr = new float[vertices.size()];
        for (int i = 0; i < vertices.size(); i++) vArr[i] = vertices.get(i);
        
        int[] iArr = new int[indices.size()];
        for (int i = 0; i < indices.size(); i++) iArr[i] = indices.get(i);

        // ★ 法線を計算する前にスムージングを適用する！
        // iterations(回数): 3〜5回が標準的。多すぎるとメッシュが縮みます。
        // alpha(強さ): 0.5 が標準的。
        applyLaplacianSmoothing(vArr, iArr, 3, 0.5f);

        // 構築し、滑らかになった頂点とインデックスを使ってスムース法線を計算
        float[] nArr = new float[vertices.size()];
        calculateNormals(vArr, nArr, iArr);

        MeshData mesh = new MeshData(vArr, nArr, iArr);
        
        return mesh;
	}

	// ----------------------------------------------------
	// ボクセルの値を安全に取得するヘルパー
	// byte型の -128〜127 を 0〜255 の float に変換して返します
	// ----------------------------------------------------
	private static float getVoxelValue(byte[] data, int x, int y, int z, int w, int h) {
		int index = x + (y * w) + (z * w * h);
		return data[index] & 0xFF; // Unsigned化
	}

	// ----------------------------------------------------
	// 線形補間 (Linear Interpolation) による正確な交点計算
	// 2つの頂点の間で、isoLevel（閾値）とぴったり交差する座標を割り出します
	// ----------------------------------------------------
	private static Vector3f vertexInterp(float isoLevel, Vector3f p1, Vector3f p2, float val1, float val2) {
		// 値が同じ、または isoLevel に完全に一致する場合は端点を返す
		if (Math.abs(isoLevel - val1) < 0.00001f)
			return new Vector3f(p1);
		if (Math.abs(isoLevel - val2) < 0.00001f)
			return new Vector3f(p2);
		if (Math.abs(val1 - val2) < 0.00001f)
			return new Vector3f(p1);

		// 割合 (mu) を計算して交点を求める
		float mu = (isoLevel - val1) / (val2 - val1);
		float x = p1.x + mu * (p2.x - p1.x);
		float y = p1.y + mu * (p2.y - p1.y);
		float z = p1.z + mu * (p2.z - p1.z);

		return new Vector3f(x, y, z);
	}
	
	// ----------------------------------------------------
    // スムース法線（Vertex Normals）の計算
    // すべての面の向き（外積）を計算し、共有する頂点に足し合わせて平均化します
    // ----------------------------------------------------
    private static void calculateNormals(float[] vertices, float[] normals, int[] indices) {
        // 1. 各三角形（面）の法線を計算し、それを構成する3つの頂点に足し合わせる
        for (int i = 0; i < indices.length; i += 3) {
            int i0 = indices[i] * 3;
            int i1 = indices[i + 1] * 3;
            int i2 = indices[i + 2] * 3;

            // 3つの頂点座標を取得
            Vector3f v0 = new Vector3f(vertices[i0], vertices[i0 + 1], vertices[i0 + 2]);
            Vector3f v1 = new Vector3f(vertices[i1], vertices[i1 + 1], vertices[i1 + 2]);
            Vector3f v2 = new Vector3f(vertices[i2], vertices[i2 + 1], vertices[i2 + 2]);

            // 辺のベクトル (v0 -> v1) と (v0 -> v2)
            Vector3f edge1 = new Vector3f();
            v1.sub(v0, edge1);
            Vector3f edge2 = new Vector3f();
            v2.sub(v0, edge2);

            // 外積（クロス積）で面の向き（法線）を求める
            Vector3f faceNormal = new Vector3f();
            edge1.cross(edge2, faceNormal);

            // 面積に比例した法線ベクトルを各頂点に加算（あとで正規化して平均化される）
            normals[i0] += faceNormal.x; normals[i0 + 1] += faceNormal.y; normals[i0 + 2] += faceNormal.z;
            normals[i1] += faceNormal.x; normals[i1 + 1] += faceNormal.y; normals[i1 + 2] += faceNormal.z;
            normals[i2] += faceNormal.x; normals[i2 + 1] += faceNormal.y; normals[i2 + 2] += faceNormal.z;
        }

        // 2. 足し合わせた法線ベクトルを正規化（長さを1.0に揃える）
        for (int i = 0; i < normals.length; i += 3) {
            Vector3f n = new Vector3f(normals[i], normals[i + 1], normals[i + 2]);
            if (n.lengthSquared() > 0) {
                n.normalize();
                normals[i] = n.x;
                normals[i + 1] = n.y;
                normals[i + 2] = n.z;
            }
        }
    }
    
 // ----------------------------------------------------
    // ラプラシアンスムージング (Laplacian Smoothing)
    // 頂点を周囲の頂点の平均位置に近づけることで、階段状のメッシュを滑らかにします
    // ----------------------------------------------------
    private static void applyLaplacianSmoothing(float[] vertices, int[] indices, int iterations, float alpha) {
        int numVertices = vertices.length / 3;

        // 1. 各頂点の「隣接する頂点リスト(Adjacency List)」を作成
        // 重複を避けるために配列の代わりに HashSet を使うと便利ですが、
        // 今回はパフォーマンスと依存関係削減のため、簡略化したリスト構造を使います。
        java.util.List<java.util.Set<Integer>> adjacency = new java.util.ArrayList<>(numVertices);
        for (int i = 0; i < numVertices; i++) {
            adjacency.add(new java.util.HashSet<>());
        }

        for (int i = 0; i < indices.length; i += 3) {
            int v0 = indices[i];
            int v1 = indices[i + 1];
            int v2 = indices[i + 2];
            
            adjacency.get(v0).add(v1); adjacency.get(v0).add(v2);
            adjacency.get(v1).add(v0); adjacency.get(v1).add(v2);
            adjacency.get(v2).add(v0); adjacency.get(v2).add(v1);
        }

        float[] tempVertices = new float[vertices.length];

        // 2. 指定された回数(iterations)だけスムージングを繰り返す
        for (int iter = 0; iter < iterations; iter++) {
            // 計算中に元の座標が上書きされないよう、現在の状態をコピー
            System.arraycopy(vertices, 0, tempVertices, 0, vertices.length);

            for (int i = 0; i < numVertices; i++) {
                java.util.Set<Integer> neighbors = adjacency.get(i);
                if (neighbors.isEmpty()) continue;

                float sumX = 0, sumY = 0, sumZ = 0;
                for (int neighbor : neighbors) {
                    sumX += tempVertices[neighbor * 3];
                    sumY += tempVertices[neighbor * 3 + 1];
                    sumZ += tempVertices[neighbor * 3 + 2];
                }

                int n = neighbors.size();
                float avgX = sumX / n;
                float avgY = sumY / n;
                float avgZ = sumZ / n;

                // 現在の位置から平均位置へ、alphaの強さ(0.0〜1.0)で移動させる
                vertices[i * 3]     += alpha * (avgX - tempVertices[i * 3]);
                vertices[i * 3 + 1] += alpha * (avgY - tempVertices[i * 3 + 1]);
                vertices[i * 3 + 2] += alpha * (avgZ - tempVertices[i * 3 + 2]);
            }
        }
        
        Log.logger.info("Mesh smoothing applied (Iterations: " + iterations + ")");
    }

